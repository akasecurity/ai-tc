// The script hooks.json runs for a hook the server can run: it sends the hook's
// stdin to the server over its unix socket and prints the answer, and runs the
// node hook itself whenever it cannot get one. Generated into scripts/ at build
// time, with the plugin version in the socket name.
//
// Everything on the fast path is a shell builtin except `cat` and `perl`, which
// is what keeps a call near the cost of two small processes rather than a node
// start. perl is the socket client because it can send the request, close its
// sending side and then wait for the answer; the nc found on some systems quits
// as soon as its input ends, before a slow answer arrives. The slow paths (no
// server yet, no perl, a refused request) are the original node hook, so the
// script can only make a call faster.
//
// Opt out with AKA_HOOK_SERVER=0 in the environment the host runs hooks in.
import { PRESENCE_ONLY_ENV, VALUE_ENV } from './forwarded-env.ts';

/** How long the shell client waits for an answer before it runs the node hook itself. */
export const CLIENT_GIVE_UP_MS = 9000;

// Connects to the unix socket named by the first argument, sends its standard
// input, closes its sending side, and prints what comes back. Gives up after 9
// seconds, inside the host's 10-second hook budget. A complete answer ends with
// a \x01 byte that no JSON payload contains; without it the answer was cut off.
const PERL_CLIENT = [
  'use Socket;binmode STDIN;binmode STDOUT;local $/;my $q=<STDIN>;',
  `$SIG{ALRM}=sub{exit 1};alarm ${String(CLIENT_GIVE_UP_MS / 1000)};`,
  'socket(S,PF_UNIX,SOCK_STREAM,0)or exit 1;',
  'connect(S,sockaddr_un($ARGV[0]))or exit 1;',
  'for(my $o=0;$o<length $q;){my $n=syswrite(S,$q,length($q)-$o,$o);defined $n or exit 1;$o+=$n}',
  'shutdown(S,1);',
  'while(sysread(S,my $b,65536)){print $b}',
  'print "\\x01";',
].join('');

/** `NAME` words for a shell `for` list; every name is a fixed upper-case identifier. */
function words(names: readonly string[]): string {
  return names.join(' ');
}

export function hookClientScript(pluginVersion: string): string {
  if (!/^[0-9A-Za-z.+-]+$/.test(pluginVersion)) {
    throw new Error(`hook client: unusable plugin version ${JSON.stringify(pluginVersion)}`);
  }
  return [
    '#!/bin/sh',
    '# Generated by tsup from src/hooks/hook-server/client-script.ts; do not edit.',
    '# Runs a hook through the hook server, or the node hook itself when there is no answer.',
    // Byte-wise length for the payload size below; the caller's locale is put
    // back before node starts, so the hook sees the environment it always did.
    '[ -n "${LC_ALL+set}" ] && caller_lc_all=$LC_ALL',
    'LC_ALL=C',
    'hook=$1',
    'case $0 in *[/\\\\]*) dir=${0%[/\\\\]*} ;; *) dir=. ;; esac',
    // The sentinel keeps the trailing newlines command substitution would strip.
    'input=$(cat; printf x)',
    'input=${input%x}',
    'fallback() {',
    '  if [ -n "${caller_lc_all+set}" ]; then LC_ALL=$caller_lc_all; else unset LC_ALL; fi',
    '  printf \'%s\' "$input" | node "$dir/$hook.js"',
    '  exit $?',
    '}',
    '[ "$AKA_HOOK_SERVER" = 0 ] && fallback',
    '[ -n "$HOME" ] || fallback',
    'command -v perl >/dev/null 2>&1 || fallback',
    "nl='",
    "'",
    'run=$HOME/.aka/run',
    `sock=$run/hook-${pluginVersion}.sock`,
    'if [ -S "$sock" ]; then',
    '  request="AKA-HOOK 1 $hook$nl"',
    '  case $PWD in \'\'|*"$nl"*) ;; *) request="${request}C $PWD$nl" ;; esac',
    `  for name in ${words(VALUE_ENV)}; do`,
    '    eval "isset=\\${$name+x}"',
    '    [ -n "$isset" ] || continue',
    '    eval "value=\\$$name"',
    '    case $value in *"$nl"*) ;; *) request="${request}E $name $value$nl" ;; esac',
    '  done',
    // Credentials are tested for presence only, so the value stays here.
    `  for name in ${words(PRESENCE_ONLY_ENV)}; do`,
    '    eval "value=\\$$name"',
    '    [ -n "$value" ] && request="${request}E $name 1$nl"',
    '  done',
    '  request="${request}P ${#input}$nl"',
    `  reply=$(printf '%s%s' "$request" "$input" | perl -e '${PERL_CLIENT}' "$sock" 2>/dev/null)`,
    "  end=$(printf '\\001')",
    '  case $reply in',
    '    "OK$nl"*"$end") reply=${reply%"$end"}; printf \'%s\' "${reply#OK"$nl"}"; exit 0 ;;',
    // The server is there and declined this one (too large, queue full).
    '    FALLBACK*) fallback ;;',
    '  esac',
    'fi',
    // No answer: no server, or a dead one that left its socket behind (the
    // server removes a stale socket as it starts). Start one for the next call,
    // once, and run this one the old way.
    `lock=$run/hook-${pluginVersion}.starting`,
    '(umask 077; mkdir -p "$run") 2>/dev/null',
    'if mkdir "$lock" 2>/dev/null; then',
    '  node "$dir/hook-server.js" --daemonize </dev/null >/dev/null 2>&1 &',
    // A lock a server never released (it was killed while starting).
    'elif [ -n "$(find "$lock" -maxdepth 0 -mmin +1 2>/dev/null)" ]; then',
    '  rmdir "$lock" 2>/dev/null',
    'fi',
    'fallback',
    '',
  ].join('\n');
}
