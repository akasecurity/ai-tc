// @ts-check
import {
  base,
  drizzleWallRules,
  noDrizzleImports,
  rootConfigFiles,
  untypedSource,
} from '@akasecurity/eslint-config';

// The selectors the package wall carries: the entry below sets
// `no-restricted-syntax` for the hooks and mod helpers, which replaces the
// wall's value for those files, so it lists them again beside its own.
const wallRule = drizzleWallRules()['no-restricted-syntax'];
const wallSelectors = Array.isArray(wallRule) ? wallRule.slice(1) : [];

const STAMPED_ONLY =
  'A hook records a capture, asks whether the organization governs an event and builds a ' +
  'model-refusal row only through src/hooks/stamped-capture.ts, whose functions take the key ' +
  "the session's account scope stamped.";

// Each name is refused as a member call, as a member call by a computed literal (a string, or a
// template with no expression) and as a plain call, which is how a destructured or imported
// function is called. The two policy functions are also refused as import specifiers, so renaming
// one on import does not hide it.
// A selector cannot follow a binding, so the rule does not see a call whose name is held in a
// variable or built by a template with an expression, a call through a binding renamed on the way
// (`const send = runtime.capture`, `const { capture: send } = runtime`) or an indirect call
// (`runtime.capture.call(...)`).
const STAMPED_NAMES = ['capture', 'captureDeferred', 'governanceApplies', 'buildModelRefusalEvent'];
const STAMPED_IMPORTS = ['governanceApplies', 'buildModelRefusalEvent'].join('|');
const stampedOnlySelectors = [
  ...STAMPED_NAMES.flatMap((name) => [
    `CallExpression[callee.name='${name}']`,
    `CallExpression[callee.property.name='${name}']`,
    `CallExpression[callee.property.value='${name}']`,
    `CallExpression[callee.property.type='TemplateLiteral'][callee.property.expressions.length=0][callee.property.quasis.0.value.cooked='${name}']`,
  ]),
  `ImportSpecifier[imported.name=/^(${STAMPED_IMPORTS})$/]`,
  `ImportSpecifier[imported.value=/^(${STAMPED_IMPORTS})$/]`,
].map((selector) => ({ selector, message: STAMPED_ONLY }));

export default [
  // hooks/engine.js is generated by build/engine.mjs and git-ignored.
  { ignores: ['test/mod-runtime/**', 'hooks/engine.js'] },
  ...base,
  ...noDrizzleImports,
  {
    languageOptions: {
      parserOptions: {
        projectService: true,
        tsconfigRootDir: import.meta.dirname,
      },
    },
  },
  {
    // SessionStart reads the interface the HOST stamps on its own subprocess
    // environment (terminal, the VS Code panel, the desktop app). Nothing else
    // in a hook's payload distinguishes them, and the transcript cannot: the
    // record carrying `entrypoint` does not exist yet when a fresh session
    // starts.
    files: ['src/hooks/session-start.ts'],
    rules: {
      'n/no-process-env': 'off',
    },
  },
  {
    // The PreToolUse hook asks whether the host is serving a Remote Control
    // session; the host marks that only in its own subprocess environment.
    files: ['src/hooks/remote-session.ts'],
    rules: {
      'n/no-process-env': 'off',
    },
  },
  {
    files: ['src/hooks/**/*.ts', 'src/mod/**/*.ts'],
    ignores: ['src/hooks/stamped-capture.ts'],
    rules: {
      'no-restricted-syntax': ['error', ...wallSelectors, ...stampedOnlySelectors],
    },
  },
  ...rootConfigFiles,
  // Tracked source outside the tsconfig: the mod (its `claude-code` types are
  // provided by the host), the engine build script and the state contract. Still
  // behind the network ban; only the type-aware rules are off.
  ...untypedSource(['build/**', 'hooks/**', 'types/**']),
];
