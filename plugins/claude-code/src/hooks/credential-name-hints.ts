// The cheap first look at a Read or Grep path: does it name a file a
// credential rule could be about? Two consumers share this one list:
//
//   - pre-tool-use-fields.ts, which captures a path for scanning only when it
//     passes `mayNameCredentialFile`;
//   - the path gate (`pathGateScript`, written to scripts/path-gate.sh at
//     build), which the manifest runs for Read and Grep INSTEAD of node. Node
//     alone costs 70-120 ms to start; the gate costs a shell, so the ordinary
//     Read (source, docs, logs) never starts node at all, and only a call
//     whose input holds a hint is handed on to pre-tool-use.js.
//
// The gate must stay a SUPERSET of `mayNameCredentialFile`: a path the hook
// would capture and the gate drops is a silent miss. It is, by construction:
// it matches the same fragments, ASCII-case-insensitively, anywhere in the
// tool input rather than only in the last path segment, and it forwards any
// input holding non-ASCII text or a \u escape, the two places where
// JavaScript's toLowerCase and a byte-wise shell match could disagree.
//
// Kept free of imports so tsup.config.ts can load it at build time.

/**
 * The name fragments a credential file carries. A superset of what
 * command-risk/credential-file-access matches: the rule, and the policy
 * assigned to it, still make the decision.
 */
export const CREDENTIAL_NAME_HINTS: readonly string[] = [
  'env',
  'netrc',
  'pgpass',
  'credential',
  'auth.json',
  'id_',
  'rsa',
  'dsa',
  'ed25519',
  '.pem',
  '.key',
  'zshrc',
  'zprofile',
  'bashrc',
  'bash_profile',
  'npmrc',
];

/** Credential files named by their directory, not their file name (~/.aws/config). */
const CREDENTIAL_DIR_HINTS: readonly string[] = ['.aws'];

export function mayNameCredentialFile(path: string): boolean {
  const lower = path.toLowerCase();
  const base = lower.slice(Math.max(lower.lastIndexOf('/'), lower.lastIndexOf('\\')) + 1);
  if (
    CREDENTIAL_DIR_HINTS.some((dir) =>
      new RegExp(String.raw`[\\/]${escapeRegExp(dir)}[\\/]`).test(lower),
    )
  ) {
    return true;
  }
  return CREDENTIAL_NAME_HINTS.some((hint) => base.includes(hint));
}

function escapeRegExp(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\]/g, String.raw`\$&`);
}

/** One hint as a case-insensitive sh glob: `env` → `*[eE][nN][vV]*`. */
function shellGlob(hint: string): string {
  let glob = '';
  for (const ch of hint) {
    if (/[a-z]/.test(ch)) glob += `[${ch}${ch.toUpperCase()}]`;
    else if (/[0-9._-]/.test(ch)) glob += ch;
    else
      throw new Error(
        `credential hint ${JSON.stringify(hint)} holds ${ch}, which the gate cannot match`,
      );
  }
  return `*${glob}*`;
}

/**
 * The POSIX sh source of scripts/path-gate.sh. It reads the hook payload, and
 * hands it unchanged to pre-tool-use.js beside it only when the tool input
 * could name a credential file; otherwise it exits 0 with no output, which is
 * the same "allow unchanged" the node hook answers for such a path.
 *
 * The match runs on the payload from the `"tool_input":` key onward, so the
 * session id, transcript path and cwd before it cannot trigger node. If the
 * key is absent the whole payload is matched, which only forwards more.
 */
export function pathGateScript(): string {
  const globs = [...CREDENTIAL_NAME_HINTS, ...CREDENTIAL_DIR_HINTS].map(shellGlob);
  return [
    '#!/bin/sh',
    '# Generated by tsup from src/hooks/credential-name-hints.ts; do not edit.',
    '# Read/Grep fast path: start node only for input that may name a credential file.',
    // Byte-wise matching for the ranges below; the caller's locale is put back
    // before node starts, so the hook sees the environment it always did.
    '[ -n "${LC_ALL+set}" ] && caller_lc_all=$LC_ALL',
    'LC_ALL=C',
    'input=$(cat)',
    'rest=${input#*\\"tool_input\\":}',
    'case $0 in *[/\\\\]*) dir=${0%[/\\\\]*} ;; *) dir=. ;; esac',
    'forward() {',
    '  if [ -n "${caller_lc_all+set}" ]; then LC_ALL=$caller_lc_all; else unset LC_ALL; fi',
    '  printf \'%s\' "$input" | node "$dir/pre-tool-use.js"',
    '  exit $?',
    '}',
    'case $rest in',
    `  ${globs.join('|')}) forward ;;`,
    // Non-ASCII text or a \u escape: let the hook decide rather than match
    // bytes. Tab and newline are the whitespace a pretty-printed payload adds.
    '  *\\\\u[0-9a-fA-F][0-9a-fA-F][0-9a-fA-F][0-9a-fA-F]*) forward ;;',
    "  *[!\\ -~'\t''\n']*) forward ;;",
    'esac',
    'exit 0',
    '',
  ].join('\n');
}
